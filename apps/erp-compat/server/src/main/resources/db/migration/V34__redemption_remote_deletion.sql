ALTER TABLE erp_compat_redemption_code_issues ADD COLUMN IF NOT EXISTS remote_deletion_state VARCHAR(20);
CREATE TABLE IF NOT EXISTS erp_compat_redemption_deletions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_issue_id BIGINT NOT NULL UNIQUE REFERENCES erp_compat_redemption_code_issues(id),
 requested_issue_id BIGINT NOT NULL REFERENCES erp_compat_redemption_code_issues(id),
 configuration_id VARCHAR(255) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('CHECKED','DELETING','UNKNOWN','DELETED')),
 snapshot_json TEXT NOT NULL, remote_json TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 remote_attempted BOOLEAN NOT NULL DEFAULT FALSE,
 row_version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS erp_compat_redemption_task_deletions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id BIGINT NOT NULL REFERENCES erp_compat_redemption_code_tasks(id),
 status VARCHAR(20) NOT NULL CHECK (status IN ('CHECKING','CHECKED','RUNNING','PAUSED','FINISHED','STOPPED')),
 scope_json TEXT NOT NULL, items_json TEXT NOT NULL, busy BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 row_version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_redemption_task_deletion_task ON erp_compat_redemption_task_deletions(task_id,id);
