create table erp_compat_redemption_recoveries (
    id bigint generated by default as identity primary key,
    owner_issue_id bigint not null references erp_compat_redemption_code_issues(id),
    requested_issue_id bigint not null,
    remote_market_id bigint not null,
    key_number integer not null, account_id bigint not null,
    old_configuration_id varchar(255) not null,
    new_configuration_id varchar(255), new_group_key varchar(255),
    status varchar(30) not null,
    reason varchar(1000), snapshot_json text not null, history_json text not null,
    proof_rows integer not null default 0, proof_pages integer not null default 0,
    checked_at timestamp with time zone, created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null, row_version bigint not null default 0,
    unique(owner_issue_id, old_configuration_id),
    foreign key(requested_issue_id, remote_market_id) references erp_compat_redemption_code_issues(id, remote_market_id),
    check(key_number between 1 and 1000 and remote_market_id > 0),
    check(new_configuration_id is null or new_configuration_id <> old_configuration_id),
    foreign key(owner_issue_id, remote_market_id) references erp_compat_redemption_code_issues(id, remote_market_id),
    check(status in ('CHECK_UNAVAILABLE','PRESENT','MISSING','CREATING','UNCONFIRMED','RECEIPT_SAVED','APPLYING','COMPLETED'))
);
alter table erp_compat_redemption_code_issues add column active_recovery_id bigint
    references erp_compat_redemption_recoveries(id);
alter table erp_compat_redemption_code_issues add column pending_recovery_id bigint
    references erp_compat_redemption_recoveries(id);
alter table erp_compat_redemption_code_issues add column current_recovery_id bigint
    references erp_compat_redemption_recoveries(id);
alter table erp_compat_redemption_code_issues add column inventory_configuration_id varchar(255);
create table erp_compat_redemption_historical_codes (
    id bigint generated by default as identity primary key,
    recovery_id bigint not null references erp_compat_redemption_recoveries(id),
    owner_issue_id bigint not null,
    remote_market_id bigint not null, configuration_id varchar(255) not null, code_index integer not null, code varchar(255) not null,
    foreign key(owner_issue_id, remote_market_id) references erp_compat_redemption_code_issues(id, remote_market_id),
    unique(recovery_id, code_index)
);
create index ix_redemption_historical_market_code on erp_compat_redemption_historical_codes(remote_market_id, code);

create table erp_compat_redemption_policy_updates (
 id bigint generated by default as identity primary key,
 owner_issue_id bigint not null, requested_issue_id bigint not null, remote_market_id bigint not null,
 configuration_id varchar(255) not null, plan_key varchar(64) not null,
 status varchar(30) not null, reason varchar(1000), snapshot_json text not null, history_json text not null,
 created_at timestamp with time zone not null, updated_at timestamp with time zone not null,
 row_version bigint not null default 0, unique(owner_issue_id,plan_key),
 foreign key(owner_issue_id,remote_market_id) references erp_compat_redemption_code_issues(id,remote_market_id),
 foreign key(requested_issue_id,remote_market_id) references erp_compat_redemption_code_issues(id,remote_market_id),
 check(status in ('CHECKED','UPDATING','UNCONFIRMED','UPDATED','APPLIED'))
);
alter table erp_compat_redemption_code_issues add column policy_update_id bigint references erp_compat_redemption_policy_updates(id);
